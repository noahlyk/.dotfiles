#!/usr/bin/env bash
# Generates ../dead-mod-binds.kdl: binds every Mod+<key> (with every
# Shift/Ctrl/Alt combo) to a no-op so unbound Super chords are swallowed
# instead of passing through to the focused window. Real binds win because
# config.kdl includes the output BEFORE any real binds (later wins per key).
# Re-run after adding new keys here; no need to re-run when adding real binds.
out="${XDG_CONFIG_HOME:-$HOME/.config}/niri/dead-mod-binds.kdl"
keys=({a..z} {0..9} F{1..24} Space Return Tab Escape BackSpace Delete Insert Home End
  Page_Up Page_Down Left Right Up Down Comma Period Slash Semicolon Apostrophe Grave
  Minus Equal BracketLeft BracketRight Backslash Print)
mods=("" "Shift+" "Ctrl+" "Alt+" "Shift+Ctrl+" "Shift+Alt+" "Ctrl+Alt+" "Shift+Ctrl+Alt+")
{
  echo "// GENERATED by scripts/gen-dead-mod-binds.sh, do not edit."
  echo "// Swallows unbound Super chords. Overridden by every real bind (see config.kdl)."
  echo "binds {"
  for m in "${mods[@]}"; do for k in "${keys[@]}"; do
    echo "    Mod+${m}${k} { spawn \"true\"; }"
  done; done
  echo "}"
} > "$out"
